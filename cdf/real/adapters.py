import asyncio
import re
import time
from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional

from pydantic import BaseModel


class LLMResponse(BaseModel):
    text: str
    input_tokens: Optional[int] = None
    output_tokens: Optional[int] = None
    total_tokens: Optional[int] = None
    finish_reason: Optional[str] = None
    latency: float = 0.0
    model: str = ""
    error: Optional[str] = None


class BaseLLMAdapter(ABC):
    def __init__(
        self,
        model: str,
        api_key: str,
        base_url: Optional[str] = None,
        timeout: int = 60,
        max_retries: int = 5,
        temperature: float = 0.0,
    ):
        self.model = model
        self.api_key = api_key
        self.base_url = base_url
        self.timeout = timeout
        self.max_retries = max_retries
        self.temperature = temperature

    @abstractmethod
    async def generate(
        self,
        messages: List[Dict[str, str]],
        seed: int = 0,
    ) -> LLMResponse:
        pass


class OpenAICompatibleAdapter(BaseLLMAdapter):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

        from openai import AsyncOpenAI

        self.client = AsyncOpenAI(
            api_key=self.api_key,
            base_url=self.base_url,
            timeout=self.timeout,
        )

    async def generate(
        self,
        messages: List[Dict[str, str]],
        seed: int = 0,
    ) -> LLMResponse:

        retries = 0
        backoff = 1.0

        while retries <= self.max_retries:
            start_time = time.time()

            try:
                response = await self.client.chat.completions.create(
                    model=self.model,
                    messages=messages,
                    temperature=self.temperature,
                    seed=seed,
                )

                latency = time.time() - start_time

                choice = response.choices[0]
                usage = response.usage

                return LLMResponse(
                    text=choice.message.content or "",
                    input_tokens=(
                        usage.prompt_tokens
                        if usage
                        else None
                    ),
                    output_tokens=(
                        usage.completion_tokens
                        if usage
                        else None
                    ),
                    total_tokens=(
                        usage.total_tokens
                        if usage
                        else None
                    ),
                    finish_reason=choice.finish_reason,
                    latency=latency,
                    model=response.model or self.model,
                )

            except Exception as e:
                retries += 1

                if retries > self.max_retries:
                    return LLMResponse(
                        text="",
                        latency=time.time() - start_time,
                        model=self.model,
                        error=str(e),
                    )

                await asyncio.sleep(
                    backoff
                    + (asyncio.get_event_loop().time() % 0.1)
                )

                backoff *= 2.0


class FakeAdapter(BaseLLMAdapter):
    """
    Deterministic local adapter used for dashboard/backend testing.

    It understands the same task format generated by LLMAgent:

        Initial value: 123
        Operations:
        1. add(45)
        2. reverse_digits()
        3. multiply_mod(7)

    It executes the real operation implementations from
    cdf.generator.operations and returns:

        Step 1: 168
        Step 2: 861
        Step 3: 6027

    No external API is contacted.
    """

    async def generate(
        self,
        messages: List[Dict[str, str]],
        seed: int = 0,
    ) -> LLMResponse:

        start_time = time.time()

        # Small delay so the live dashboard has time to show progress.
        await asyncio.sleep(0.01)

        try:
            if not messages:
                raise ValueError("FakeAdapter received no messages.")

            # The LLMAgent puts the task in the final user message.
            user_messages = [
                message
                for message in messages
                if message.get("role") == "user"
            ]

            if not user_messages:
                raise ValueError(
                    "FakeAdapter could not find a user message."
                )

            prompt = user_messages[-1].get("content", "")

            # ---------------------------------------------------------
            # Parse initial value
            # ---------------------------------------------------------

            initial_match = re.search(
                r"Initial\s+value:\s*(-?\d+)",
                prompt,
                flags=re.IGNORECASE,
            )

            if not initial_match:
                raise ValueError(
                    "FakeAdapter could not parse the initial value "
                    "from the task prompt."
                )

            current_value = int(initial_match.group(1))

            # ---------------------------------------------------------
            # Parse operations
            # ---------------------------------------------------------

            operations_start = re.search(
                r"Operations\s*:\s*",
                prompt,
                flags=re.IGNORECASE,
            )

            if not operations_start:
                raise ValueError(
                    "FakeAdapter could not find the Operations section."
                )

            operations_text = prompt[operations_start.end():]

            operation_lines = re.findall(
                r"^\s*\d+\.\s*(.+?)\s*$",
                operations_text,
                flags=re.MULTILINE,
            )

            if not operation_lines:
                raise ValueError(
                    "FakeAdapter found no operations in the task prompt."
                )

            # Import the project's actual operation implementations.
            from cdf.generator.operations import (
                add,
                multiply_mod,
                reverse_digits,
                rotate_digits_right,
                sum_digits,
            )

            results = []

            # ---------------------------------------------------------
            # Execute every operation sequentially
            # ---------------------------------------------------------

            for operation_text in operation_lines:

                operation = operation_text.strip()

                # add(y)
                match = re.fullmatch(
                    r"add\(\s*(-?\d+)\s*\)",
                    operation,
                    flags=re.IGNORECASE,
                )

                if match:
                    y = int(match.group(1))
                    current_value = add(current_value, y)

                else:
                    # multiply_mod(m)
                    match = re.fullmatch(
                        r"multiply_mod\(\s*(-?\d+)\s*\)",
                        operation,
                        flags=re.IGNORECASE,
                    )

                    if match:
                        m = int(match.group(1))
                        current_value = multiply_mod(
                            current_value,
                            m,
                        )

                    else:
                        # reverse_digits()
                        if re.fullmatch(
                            r"reverse_digits\(\s*\)",
                            operation,
                            flags=re.IGNORECASE,
                        ):
                            current_value = reverse_digits(
                                current_value
                            )

                        else:
                            # rotate_digits()
                            if re.fullmatch(
                                r"rotate_digits\(\s*\)",
                                operation,
                                flags=re.IGNORECASE,
                            ):
                                current_value = rotate_digits_right(
                                    current_value
                                )

                            else:
                                # sum_digits()
                                if re.fullmatch(
                                    r"sum_digits\(\s*\)",
                                    operation,
                                    flags=re.IGNORECASE,
                                ):
                                    current_value = sum_digits(
                                        current_value
                                    )

                                else:
                                    raise ValueError(
                                        f"FakeAdapter does not recognize "
                                        f"operation: {operation}"
                                    )

                results.append(current_value)

            # ---------------------------------------------------------
            # Format exactly as expected by OutputParser
            # ---------------------------------------------------------

            output = "\n".join(
                f"Step {step}: {value}"
                for step, value in enumerate(results, start=1)
            )

            prompt_tokens = max(1, len(prompt) // 4)
            output_tokens = max(1, len(output) // 4)

            return LLMResponse(
                text=output,
                input_tokens=prompt_tokens,
                output_tokens=output_tokens,
                total_tokens=prompt_tokens + output_tokens,
                finish_reason="stop",
                latency=time.time() - start_time,
                model=self.model,
            )

        except Exception as e:
            # Return a normalized error instead of silently producing
            # incorrect fake output.
            return LLMResponse(
                text="",
                input_tokens=None,
                output_tokens=None,
                total_tokens=None,
                finish_reason="error",
                latency=time.time() - start_time,
                model=self.model,
                error=str(e),
            )


def get_adapter(
    provider_id: str,
    is_openai_compatible: bool,
    **kwargs,
) -> BaseLLMAdapter:

    if provider_id == "fake":
        return FakeAdapter(**kwargs)

    elif is_openai_compatible:
        return OpenAICompatibleAdapter(**kwargs)

    else:
        # For non-compatible providers, e.g. native Gemini,
        # a dedicated adapter can be implemented later.
        raise NotImplementedError(
            f"Provider {provider_id} adapter not yet implemented."
        )